-- =====================================================================
-- FPSS 2027 — LOTES DE PREÇO POR PRODUTO (ex.: churrasco 1º lote R$60,
-- 2º lote R$70, "Dia da festa" R$75).
--
-- Cada lote tem: nome, preço, limite de quantidade (opcional) e data
-- "válido até" (opcional, editável). O site usa o primeiro lote
-- vigente (ativo + dentro da data + ainda com saldo), na ordem.
-- Produto SEM lotes continua usando produtos.preco como sempre.
--
-- Rode este arquivo UMA vez no SQL Editor do Supabase.
-- =====================================================================

create table if not exists public.produto_lotes (
  id                bigint generated by default as identity primary key,
  produto_id        bigint not null references public.produtos(id) on delete cascade,
  nome              text not null,
  preco             numeric(10,2) not null check (preco >= 0),
  quantidade_limite integer check (quantidade_limite is null or quantidade_limite > 0),
  valido_ate        date,
  ordem             integer not null default 0,
  ativo             boolean not null default true,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create index if not exists produto_lotes_produto_idx on public.produto_lotes (produto_id, ordem);
alter table public.produto_lotes enable row level security;

-- Cada item do pedido guarda de qual lote veio (para relatórios)
alter table public.pedido_itens
  add column if not exists lote_id   bigint references public.produto_lotes(id) on delete set null,
  add column if not exists lote_nome text;

create index if not exists pedido_itens_lote_idx on public.pedido_itens (lote_id);

-- Quanto já foi vendido (pago) e reservado (Pix pendente criado há menos de 70 min) por lote
create or replace function public.fpss_produto_lotes_uso(p_produto_ids bigint[])
returns table (lote_id bigint, vendido integer, reservado integer)
language sql
stable
as $$
  select l.id,
         coalesce(sum(i.quantidade) filter (
           where p.status_pagamento = 'pago' and p.reembolsado_em is null), 0)::int,
         coalesce(sum(i.quantidade) filter (
           where p.status_pagamento = 'pendente' and p.reembolsado_em is null
             and p.created_at > now() - interval '70 minutes'), 0)::int
  from public.produto_lotes l
  left join public.pedido_itens i on i.lote_id = l.id
  left join public.pedidos p on p.id = i.pedido_id
  where l.produto_id = any (p_produto_ids)
  group by l.id;
$$;

revoke all on function public.fpss_produto_lotes_uso(bigint[]) from public, anon, authenticated;
grant execute on function public.fpss_produto_lotes_uso(bigint[]) to service_role;

-- Conferência
select 'produto_lotes' as tabela, count(*) as linhas from public.produto_lotes;
