-- A paróquia recebe os blocos devolvidos pelas comunidades e depois
-- repassa (dinheiro + cartelas de papel) para a equipe do site.
--   paroquia_recebimentos        1 linha por recebimento (comunidade, valores, data, quem lançou)
--   paroquia_recebimento_blocos  os blocos de cada recebimento (vendidas / voltaram / pagas no site)
--   paroquia_repasses            1 linha por repasse da paróquia para a equipe
-- Não mexe em nada dos Blocos (acertos, cartelas, planos).
-- =====================================================================

create table if not exists public.paroquia_repasses (
  id                bigint generated by default as identity primary key,
  data_repasse      date not null,
  esperado_dinheiro numeric(12,2) not null default 0,
  esperado_pix      numeric(12,2) not null default 0,
  esperado_cartao   numeric(12,2) not null default 0,
  dinheiro          numeric(12,2) not null default 0,
  pix               numeric(12,2) not null default 0,
  cartao            numeric(12,2) not null default 0,
  blocos            int not null default 0,
  observacao        text,
  lancador_id       uuid,
  lancador_nome     text,
  cancelado         boolean not null default false,
  cancelado_por     text,
  cancelado_em      timestamptz,
  created_at        timestamptz not null default now()
);

create table if not exists public.paroquia_recebimentos (
  id               bigint generated by default as identity primary key,
  responsavel_id   bigint not null references public.blocos_responsaveis(id),
  responsavel_nome text,
  comunidade       text,
  dinheiro         numeric(12,2) not null default 0,
  pix              numeric(12,2) not null default 0,
  cartao           numeric(12,2) not null default 0,
  observacao       text,
  lancador_id      uuid,
  lancador_nome    text,
  repasse_id       bigint references public.paroquia_repasses(id),
  cancelado        boolean not null default false,
  cancelado_por    text,
  cancelado_em     timestamptz,
  created_at       timestamptz not null default now()
);
create index if not exists paroquia_recebimentos_resp_idx on public.paroquia_recebimentos (responsavel_id);
create index if not exists paroquia_recebimentos_repasse_idx on public.paroquia_recebimentos (repasse_id);

create table if not exists public.paroquia_recebimento_blocos (
  id              bigint generated by default as identity primary key,
  recebimento_id  bigint not null references public.paroquia_recebimentos(id) on delete cascade,
  entrega_id      bigint not null references public.blocos_entregas(id),
  sequencial      int,
  numero_inicial  int,
  numero_final    int,
  quantidade      int not null default 0,
  vendidas        int not null default 0,
  devolvidas      int not null default 0,
  pagas_site      int not null default 0,
  ativo           boolean not null default true
);
-- um bloco só pode estar em UM recebimento válido (evita receber duas vezes)
create unique index if not exists paroquia_bloco_unico_idx on public.paroquia_recebimento_blocos (entrega_id) where ativo;
create index if not exists paroquia_recebimento_blocos_rec_idx on public.paroquia_recebimento_blocos (recebimento_id);

-- quanto a comunidade devia entregar (vendas - comissao - pagas no site), calculado na hora do recebimento
alter table public.paroquia_recebimentos add column if not exists a_receber numeric(12,2) not null default 0;
alter table public.paroquia_recebimento_blocos add column if not exists devido numeric(12,2) not null default 0;
alter table public.paroquia_recebimento_blocos add column if not exists abate_site numeric(12,2) not null default 0;

-- Pix por QR Code gerado na paróquia (mesma tabela do Acerto, para a equipe ver o Pix ao acertar a comunidade)
alter table public.blocos_acerto_pix add column if not exists origem text;
alter table public.blocos_acerto_pix add column if not exists recebimento_id bigint;

-- quais comunidades devolvem os blocos na paróquia (a tela da paróquia mostra só essas por padrão)
alter table public.blocos_comunidades add column if not exists devolve_paroquia boolean not null default false;

-- só o servidor (service_role) acessa
do $$
declare t text;
begin
  foreach t in array array['paroquia_repasses','paroquia_recebimentos','paroquia_recebimento_blocos'] loop
    execute format('revoke all on public.%I from public', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then execute format('revoke all on public.%I from anon', t); end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then execute format('revoke all on public.%I from authenticated', t); end if;
    if exists (select 1 from pg_roles where rolname = 'service_role') then execute format('grant all on public.%I to service_role', t); end if;
  end loop;
end $$;

