-- =====================================================================
-- BLOCOS — forma de pagamento do acerto + cruzamento com cartelas pagas no site
-- Rode no SQL Editor do Supabase.
-- =====================================================================

-- 1. pagamentos de cada acerto: dinheiro, pix, cartão (débito/crédito) e
--    "pix_site" = cartelas que o cliente já pagou direto no site (o dinheiro
--    entrou na festa, então abate o que o distribuidor deve repassar)
create table if not exists public.blocos_acerto_pagamentos (
  id         bigint generated by default as identity primary key,
  acerto_id  bigint not null references public.blocos_acertos(id) on delete cascade,
  forma      text not null check (forma in ('dinheiro','pix','cartao_debito','cartao_credito','pix_site')),
  valor      numeric(12,2) not null check (valor > 0),
  detalhe    jsonb,
  created_at timestamptz not null default now()
);
create index if not exists blocos_acerto_pag_acerto_idx on public.blocos_acerto_pagamentos (acerto_id);
alter table public.blocos_acerto_pagamentos enable row level security;

-- 2. quais cartelas (número do bloco, só a parte antes do "-") já constam PAGAS
--    na tabela de cartelas do site (Pix online ou baixa manual)
create or replace function public.fpss_blocos_cartelas_pagas(p_numeros int[])
returns table (numero int, numero_chance1 text, tipo text, nome_comprador text,
               valor_pago numeric, data_pagamento timestamptz, via_pix boolean)
language sql stable as $$
  select (case when c.numero_chance1 ~ '^[0-9]+-[0-9]+$' then split_part(c.numero_chance1, '-', 1)::int end) as numero,
         c.numero_chance1, c.tipo, c.nome_comprador, c.valor_pago, c.data_pagamento,
         (c.pix_id is not null) as via_pix
    from public.cartelas c
   where c.status = 'pago'
     and (case when c.numero_chance1 ~ '^[0-9]+-[0-9]+$' then split_part(c.numero_chance1, '-', 1)::int end) = any (p_numeros);
$$;

grant all on public.blocos_acerto_pagamentos to service_role;
grant execute on function public.fpss_blocos_cartelas_pagas(int[]) to service_role;
notify pgrst, 'reload schema';
