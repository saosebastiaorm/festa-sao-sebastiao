  check (role in ('admin','padrao','voluntario','operador_caixa','equipe_bingo','usuario'));

alter table public.perfis_acesso drop constraint if exists perfis_acesso_papel_check;
alter table public.perfis_acesso add constraint perfis_acesso_papel_check
  check (papel in ('padrao','voluntario','operador_caixa','equipe_bingo'));

-- telas iniciais dos perfis novos (só cria; não mexe no que você já marcou)
