-- ---------------------------------------------------------------------
-- 2. CATÁLOGO DE BLOCOS E CARTELAS
-- ---------------------------------------------------------------------
create table if not exists public.blocos (
  id              bigint generated by default as identity primary key,
  sequencial      int not null unique,
  numero_inicial  int not null,
  numero_final    int not null,
  quantidade      int generated always as (numero_final - numero_inicial + 1) stored,
  criado_por_nome text,
  created_at      timestamptz not null default now(),
  check (numero_final >= numero_inicial)
);
create index if not exists blocos_inicial_idx on public.blocos (numero_inicial);

create table if not exists public.blocos_responsaveis (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  comunidade      text,
  telefone        text,
  endereco        text,
  observacao      text,
  comunidade_id   bigint references public.blocos_comunidades(id),
  criado_por_nome text,
  created_at      timestamptz not null default now()
);
alter table public.blocos_responsaveis add column if not exists comunidade_id bigint references public.blocos_comunidades(id);
create index if not exists blocos_resp_com_idx on public.blocos_responsaveis (comunidade_id);
create index if not exists blocos_resp_nome_idx on public.blocos_responsaveis (lower(nome));

-- distribuidores: pessoas da EQUIPE que entregam os blocos (Marcos,
-- André, Rafael...). Cadastro único para não ter o mesmo nome escrito
-- de jeitos diferentes; cada entrega guarda quem entregou.
create table if not exists public.blocos_distribuidores (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  telefone   text,
  ativo      boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists blocos_distribuidores_nome_uk on public.blocos_distribuidores (lower(trim(nome)));
insert into public.blocos_distribuidores (nome)
select n from (values ('Marcos'), ('André'), ('Rafael')) v(n)
where not exists (select 1 from public.blocos_distribuidores);

create table if not exists public.blocos_recibos (
  id             bigint generated by default as identity primary key,
  responsavel_id bigint not null references public.blocos_responsaveis(id),
  assinatura     text,               -- imagem PNG (data URL) da assinatura com o dedo
  lancador_id    uuid,
  lancador_nome  text,
  created_at     timestamptz not null default now()
);

create table if not exists public.blocos_entregas (
  id                  bigint generated by default as identity primary key,
  bloco_id            bigint not null references public.blocos(id),
  responsavel_id      bigint not null references public.blocos_responsaveis(id),
  recibo_id           bigint references public.blocos_recibos(id),
  plano_id            bigint references public.blocos_planos(id),
  plano_nome          text not null,
  comissao_pct        numeric(5,2) not null default 0,
  cobra               boolean not null default true,
  preco               numeric(10,2) not null,
  quantidade_entregue int not null,
  tem_bonus           boolean not null default false,
  bonus_usado         boolean not null default true,
  status              text not null default 'ativa' check (status in ('ativa','encerrada','cancelada')),
  lancador_id         uuid,
  lancador_nome       text,
  created_at          timestamptz not null default now()
);
alter table public.blocos_entregas add column if not exists distribuidor_id bigint references public.blocos_distribuidores(id);
alter table public.blocos_entregas add column if not exists distribuidor_nome text;
alter table public.blocos_entregas add column if not exists separada boolean not null default false;
alter table public.blocos_entregas add column if not exists entregue_em timestamptz;
update public.blocos_entregas set entregue_em = created_at where entregue_em is null and not separada;
alter table public.blocos_responsaveis add column if not exists provisorio boolean not null default false;
alter table public.blocos_recibos  add column if not exists distribuidor_id bigint references public.blocos_distribuidores(id);
alter table public.blocos_recibos  add column if not exists distribuidor_nome text;
create index if not exists blocos_entregas_resp_idx on public.blocos_entregas (responsavel_id);
create index if not exists blocos_entregas_bloco_idx on public.blocos_entregas (bloco_id);

create table if not exists public.blocos_cartelas (
  numero        int primary key,
  bloco_id      bigint not null references public.blocos(id) on delete cascade,
  status        text not null default 'estoque'
                check (status in ('estoque','com_responsavel','vendida','devolvida')),
  entrega_id    bigint references public.blocos_entregas(id),
  atualizado_em timestamptz not null default now()
);
create index if not exists blocos_cartelas_bloco_idx on public.blocos_cartelas (bloco_id);
create index if not exists blocos_cartelas_entrega_idx on public.blocos_cartelas (entrega_id);
create index if not exists blocos_cartelas_status_idx on public.blocos_cartelas (status);

create table if not exists public.blocos_acertos (
  id                bigint generated by default as identity primary key,
  responsavel_id    bigint not null references public.blocos_responsaveis(id),
  vendidas          int not null default 0,
  devolvidas        int not null default 0,
  valor_bruto       numeric(12,2) not null default 0,
