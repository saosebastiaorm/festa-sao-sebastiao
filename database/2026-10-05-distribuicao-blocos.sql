-- 8. PAINEL (tudo calculado no banco, rápido mesmo com 30 mil cartelas)
-- ---------------------------------------------------------------------
create or replace function public.fpss_blocos_painel() returns jsonb
language sql stable as $$
  select jsonb_build_object(
    'config', (select to_jsonb(c) from public.blocos_config c where id = 1),
    'cartelas', (select jsonb_build_object(
        'total', count(*),
        'estoque', count(*) filter (where status = 'estoque'),
        'com_responsavel', count(*) filter (where status = 'com_responsavel'),
        'vendidas', count(*) filter (where status = 'vendida'),
        'devolvidas', count(*) filter (where status = 'devolvida'),
        'separadas', (select coalesce(sum(quantidade_entregue), 0) from public.blocos_entregas where separada and status = 'ativa')
      ) from public.blocos_cartelas),
    'blocos', (select jsonb_build_object(
        'total', count(*),
        'livres', count(*) filter (where livres = qtd),
        'na_rua', count(*) filter (where com_resp > 0)
      ) from (select b.id, b.quantidade as qtd,
                     count(*) filter (where c.status in ('estoque','devolvida')) as livres,
                     count(*) filter (where c.status = 'com_responsavel') as com_resp
              from public.blocos b join public.blocos_cartelas c on c.bloco_id = b.id group by b.id) x),
    'financeiro', (select jsonb_build_object(
        'bruto', coalesce(sum(valor_bruto), 0),
        'comissao', coalesce(sum(valor_comissao), 0),
        'devido', coalesce(sum(valor_devido), 0),
        'pago', coalesce(sum(valor_pago), 0),
        'saldo', coalesce(sum(valor_devido), 0) - coalesce(sum(valor_pago), 0),
        'acertos', count(*)
      ) from public.blocos_acertos where not desfeito),
    'por_plano', (select coalesce(jsonb_agg(p order by p->>'plano'), '[]'::jsonb) from (
        select jsonb_build_object(
          'plano', e.plano_nome,
          'entregues', sum(e.quantidade_entregue),
          'com_responsavel', sum(x.com_resp),
          'vendidas', sum(x.vend),
          'devolvidas', sum(x.dev),
          'devido', coalesce(sum(ai.devido), 0)
        ) as p
        from public.blocos_entregas e
        left join lateral (select count(*) filter (where status = 'com_responsavel') com_resp,
                                  count(*) filter (where status = 'vendida') vend,
                                  count(*) filter (where status = 'devolvida') dev
                           from public.blocos_cartelas where entrega_id = e.id) x on true
        left join lateral (select sum(i.valor_devido) devido from public.blocos_acerto_itens i
                           join public.blocos_acertos a on a.id = i.acerto_id
                           where i.entrega_id = e.id and not a.desfeito) ai on true
        where e.status <> 'cancelada'
        group by e.plano_nome) q),
    'por_lancador', (select coalesce(jsonb_agg(l order by l->>'lancador'), '[]'::jsonb) from (
        select jsonb_build_object(
          'lancador', nome,
          'entregas', sum(entregas), 'cartelas_entregues', sum(cartelas),
          'acertos', sum(acertos), 'recebido', sum(recebido)
        ) as l
        from (
          select coalesce(lancador_nome, '—') nome, count(*) entregas, sum(quantidade_entregue) cartelas, 0 acertos, 0::numeric recebido
            from public.blocos_entregas where status <> 'cancelada' group by 1
          union all
          select coalesce(lancador_nome, '—'), 0, 0, count(*), sum(valor_pago)
            from public.blocos_acertos where not desfeito group by 1
        ) u group by nome) q),
    'por_distribuidor', (select coalesce(jsonb_agg(d order by d->>'distribuidor'), '[]'::jsonb) from (
        select jsonb_build_object(
          'distribuidor', coalesce(e.distribuidor_nome, '(sem distribuidor)'),
          'blocos', count(*), 'cartelas', sum(e.quantidade_entregue),
          'com_responsavel', sum(x.com_resp), 'vendidas', sum(x.vend), 'devolvidas', sum(x.dev)
        ) as d
        from public.blocos_entregas e
        left join lateral (select count(*) filter (where status = 'com_responsavel') com_resp,
                                  count(*) filter (where status = 'vendida') vend,
                                  count(*) filter (where status = 'devolvida') dev
                           from public.blocos_cartelas where entrega_id = e.id) x on true
        where e.status <> 'cancelada'
        group by coalesce(e.distribuidor_nome, '(sem distribuidor)')) q),
    'pendentes', (select coalesce(jsonb_agg(to_jsonb(r) order by r.com_responsavel desc, r.saldo desc), '[]'::jsonb)
                  from (select id, nome, comunidade, telefone, com_responsavel, saldo, ultima_entrega
                        from public.blocos_resumo_responsavel
                        where com_responsavel > 0 or saldo > 0
                        order by com_responsavel desc, saldo desc limit 300) r)
  );
$$;

