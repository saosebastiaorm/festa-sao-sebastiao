create table if not exists public.equipes (
  id               bigint generated by default as identity primary key,
  nome             text not null,
  lider_nome       text,
  lider_telefone   text,
  previsto         integer not null default 0 check (previsto >= 0),
  disponivel       integer not null default 0 check (disponivel >= 0),
  proibe_menor     boolean not null default false,
  ativo            boolean not null default true,
  observacao       text,
  ordem            integer not null default 0,
  token            text not null unique default replace(gen_random_uuid()::text, '-', ''),
  created_at       timestamptz not null default now()
);

create table if not exists public.equipes_membros (
  id               bigint generated by default as identity primary key,
  equipe_id        bigint not null references public.equipes(id) on delete cascade,
  nome             text not null,
  telefone         text,
  endereco         text,
  data_nascimento  date not null,
  tamanho_camiseta text not null,
  origem           text not null default 'lider' check (origem in ('lider','admin')),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists equipes_membros_equipe_idx on public.equipes_membros (equipe_id);

alter table public.equipes enable row level security;
alter table public.equipes_membros enable row level security;
