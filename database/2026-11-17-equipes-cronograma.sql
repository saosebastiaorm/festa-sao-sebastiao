create table if not exists public.equipes_etapas (
  id            bigint generated by default as identity primary key,
  equipe_id     bigint not null references public.equipes(id) on delete cascade,
  titulo        text not null,
  descricao     text,                       -- orientação escrita por você
  data          date,
  hora          text,                       -- "HH:MM"
  local         text,
  observacao    text,
  realizada     boolean not null default false,
  participantes integer check (participantes is null or participantes >= 0),   -- quantos participaram
  realizada_em  timestamptz,
  origem        text not null default 'admin' check (origem in ('admin','lider')),
  ordem         integer not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
alter table public.equipes_etapas add column if not exists participantes integer check (participantes is null or participantes >= 0);
create index if not exists equipes_etapas_equipe_idx on public.equipes_etapas (equipe_id);
create index if not exists equipes_etapas_data_idx on public.equipes_etapas (data);
alter table public.equipes_etapas enable row level security;

-- As 2 etapas iniciais, para todas as equipes
insert into public.equipes_etapas (equipe_id, titulo, descricao, ordem)
select e.id, v.titulo, v.descricao, v.ordem
from public.equipes e
cross join (values
  ('Reunião de apresentação da equipe', 'Primeira reunião: apresentar a equipe, as funções e a programação.', 1),
  ('Reunião de treinamento',            'Treinamento da equipe antes da festa.', 2)
) as v(titulo, descricao, ordem)
where not exists (select 1 from public.equipes_etapas x where x.equipe_id = e.id and lower(x.titulo) = lower(v.titulo));

-- Etapas específicas do Churrasco (ajuste/apague na tela se quiser)
insert into public.equipes_etapas (equipe_id, titulo, descricao, ordem)
select e.id, v.titulo, v.descricao, v.ordem
from public.equipes e
cross join (values
  ('Abate do gado',      'Data e local do abate.', 3),
  ('Desossa e preparo',  'Data e local da desossa e do preparo da carne.', 4)
) as v(titulo, descricao, ordem)
where lower(e.nome) = 'churrasco'
  and not exists (select 1 from public.equipes_etapas x where x.equipe_id = e.id and lower(x.titulo) = lower(v.titulo));

-- Relatório (leitura)
create or replace function public.fpss_relatorio_cronograma(p_ativa text default null) returns jsonb
language plpgsql stable as $$
declare hoje date := (now() at time zone 'America/Porto_Velho')::date; v jsonb;
begin
  select coalesce(jsonb_agg(to_jsonb(x) order by x.data nulls last, x.hora nulls last, x.equipe_nome, x.ordem), '[]'::jsonb) into v from (
    select t.id, t.equipe_id, e.nome as equipe_nome, e.lider_nome, e.lider_telefone, t.titulo, t.descricao, t.data, t.hora, t.local, t.observacao,
           t.participantes, t.realizada, t.origem, t.ordem,
           case when t.realizada then 'realizada' when t.data is null then 'sem_data' when t.data < hoje then 'atrasada' else 'agendada' end as situacao
      from public.equipes_etapas t join public.equipes e on e.id = t.equipe_id
     where p_ativa is null or p_ativa = '' or (p_ativa = 'sim' and e.ativo) or (p_ativa = 'nao' and not e.ativo)) x;
  return jsonb_build_object('etapas', v);
end;
$$;
grant execute on function public.fpss_relatorio_cronograma(text) to service_role;

