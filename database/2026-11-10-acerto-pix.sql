-- Cada cobrança Pix gerada no Acerto fica registrada aqui. O valor só
-- entra no acerto depois que o Sicredi confirma o pagamento (CONCLUIDA).
-- Rode UMA vez no SQL Editor do Supabase.
-- =====================================================================

create table if not exists public.blocos_acerto_pix (
  id               bigint generated by default as identity primary key,
  responsavel_id   bigint not null,
  valor            numeric(12,2) not null check (valor > 0),
  txid             text not null unique,
  pix_copia_cola   text,
  status           text not null default 'pendente' check (status in ('pendente','pago')),
  pago_em          timestamptz,
  e2e_id           text,
  valor_pago       numeric(12,2),
  usado_em         timestamptz,
  acerto_id        bigint,
  criado_por_id    uuid,
  criado_por_nome  text,
  created_at       timestamptz not null default now()
);

create index if not exists blocos_acerto_pix_resp_idx on public.blocos_acerto_pix (responsavel_id, created_at desc);
alter table public.blocos_acerto_pix enable row level security;

select 'blocos_acerto_pix' as tabela, count(*) as linhas from public.blocos_acerto_pix;
