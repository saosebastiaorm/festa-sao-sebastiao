insert into public.pedido_itens
  (pedido_id, produto_id, produto_codigo, produto_nome, preco_unitario, quantidade, quantidade_entregue, exige_horario, created_at)
select
  p.id,
  pr.id,
  coalesce(p.produto_tipo, 'CHU'),
  coalesce(pr.nome, p.produto_tipo, 'Produto'),
  coalesce(p.valor_unitario, case when coalesce(p.quantidade,0) > 0 then p.valor_total / p.quantidade else p.valor_total end, 0),
  greatest(coalesce(p.quantidade, 1), 1),
  case when p.status_retirada = 'retirado' then greatest(coalesce(p.quantidade, 1), 1) else 0 end,
  coalesce(pr.exige_horario, false),
  p.created_at
from public.pedidos p
left join public.produtos pr on pr.codigo = coalesce(p.produto_tipo, 'CHU')
where not exists (select 1 from public.pedido_itens i where i.pedido_id = p.id);

-- Pedidos antigos já pagos: considera o estoque já "baixado" (não desconta
-- de novo o que foi vendido antes deste sistema existir).
update public.pedidos set estoque_baixado = true
where status_pagamento = 'pago' and estoque_baixado = false;

-- Estoque físico inicial = disponível + o que já foi pago e ainda não entregue
update public.produtos pr
set estoque_fisico = coalesce(pr.estoque, 0) + coalesce((
  select sum(i.quantidade - i.quantidade_entregue)
  from public.pedido_itens i
  join public.pedidos p on p.id = i.pedido_id
  where i.produto_id = pr.id and p.status_pagamento = 'pago' and p.reembolsado_em is null
), 0)
where pr.estoque_fisico is null;

insert into public.estoque_movimentos (produto_id, tipo, delta_disponivel, delta_fisico, disponivel_apos, fisico_apos, motivo)
select pr.id, 'inicial', 0, 0, pr.estoque, pr.estoque_fisico, 'Saldo inicial ao ativar o controle de estoque'
from public.produtos pr
where not exists (select 1 from public.estoque_movimentos m where m.produto_id = pr.id);

