-- Cria a tabela "divulgacoes" e a pasta pública de arquivos "divulgacoes".
-- =====================================================================

create table if not exists public.divulgacoes (
  id             bigint generated by default as identity primary key,
  slug           text not null unique,
  titulo         text not null,
  legenda        text not null,
  tipo           text not null default 'imagem' check (tipo in ('imagem','video')),
  midia_url      text,
  midia_path     text,
  og_url         text,
  og_path        text,
  criado_por     text,
  created_at     timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);

-- só o servidor (service_role) mexe na tabela
revoke all on public.divulgacoes from public;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then execute 'revoke all on public.divulgacoes from anon'; end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then execute 'revoke all on public.divulgacoes from authenticated'; end if;
  if exists (select 1 from pg_roles where rolname = 'service_role') then execute 'grant all on public.divulgacoes to service_role'; end if;
end $$;

-- pasta pública de arquivos (imagens e vídeos até 30 MB)
insert into storage.buckets (id, name, public, file_size_limit)
values ('divulgacoes', 'divulgacoes', true, 31457280)
on conflict (id) do update set public = true, file_size_limit = 31457280;

notify pgrst, 'reload schema';
