-- Cadastro de vendedores de cartela (ambulantes e outros) — 2026-10-12
-- Documentos (identificação e comprovante de residência) ficam em um bucket PRIVADO;
-- só o servidor (service_role) lê/grava, e a tela libera cada arquivo por link que expira.

create table if not exists public.vendedores_cartela (
  id                          bigint generated by default as identity primary key,
  nome                        text not null,
  cpf                         text not null,
  data_nascimento             date,
  telefone                    text,
  endereco                    text,
  bairro                      text,
  cidade                      text,
  uf                          text,
  plano_id                    bigint references public.blocos_planos(id) on delete set null,
  observacao                  text,
  doc_identificacao_path      text,
  comprovante_residencia_path text,
  ativo                       boolean not null default true,
  criado_por                  text,
  created_at                  timestamptz not null default now(),
  updated_at                  timestamptz not null default now()
);
create unique index if not exists vendedores_cartela_cpf_uq on public.vendedores_cartela (cpf);
create index if not exists vendedores_cartela_nome_idx on public.vendedores_cartela (lower(nome));
alter table public.vendedores_cartela enable row level security;   -- sem policies: só o service_role acessa

insert into storage.buckets (id, name, public)
values ('vendedores-docs', 'vendedores-docs', false)
on conflict (id) do update set public = false;
